import { lesson, rule, segment } from '../build';
import { conjugate } from '../conjugate';

/** ช่วง 4: รูป た — ผันเหมือนรูป て ทุกอย่าง เปลี่ยนแค่ตัวท้าย */
const SPECIAL = ['iku', 'kuru', 'suru'];

export const TA = segment('ta', 'たけい', 'รูป た', [
  lesson('c-ta', 'たべた', 'เปลี่ยน て เป็น た', [
    rule(
      'ta-ta',
      'て → た',
      'รูป て ลงท้าย て: เปลี่ยนเป็น た',
      [
        'รูป た คืออดีตแบบกันเอง ผันเหมือนรูป て ทุกอย่าง แล้วเปลี่ยน て เป็น た',
        'たべて → たべた · かって → かった · かいて → かいた · はなして → はなした',
      ],
      'ta',
      (v) => conjugate(v, 'te').endsWith('て') && !SPECIAL.includes(v.id),
      ['taberu', 'kau', 'kaku', 'hanasu'],
      { note: 'ใช้ต่อกับคำอื่นด้วย เช่น たことがあります (เคย…)' },
    ),
    rule(
      'ta-da',
      'で → だ',
      'รูป て ลงท้าย で: เปลี่ยนเป็น だ',
      ['คำที่รูป て ลงท้าย で (む ぶ ぬ ぐ) เปลี่ยนเป็น だ', 'のんで → のんだ · およいで → およいだ'],
      'ta',
      (v) => conjugate(v, 'te').endsWith('で'),
      ['nomu', 'asobu', 'oyogu'],
    ),
    rule(
      'ta-x',
      'いった・きた・した',
      'คำพิเศษ: いく → いった · くる → きた · する → した',
      ['คำพิเศษ 3 คำของรูป て ก็เปลี่ยน て เป็น た ตามปกติ', 'いって → いった · きて → きた · して → した'],
      'ta',
      SPECIAL,
      SPECIAL,
    ),
  ]),
]);
