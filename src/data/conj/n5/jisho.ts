import { g1, g2, lesson, rule, segment } from '../build';
import { conjugate } from '../conjugate';
import type { ConjWord } from '../types';

/**
 * ช่วง 6: ย้อนหารูปพจนานุกรม (เจอคำที่ผันแล้ว จะได้หาความหมายในพจนานุกรมได้)
 * ข้อเรียงบอกความหมายไทย เพราะบางรูปมาจากได้หลายคำ (きます · いって)
 */
const reverse = { reverse: true } as const;

/** ตัวหน้า ます */
const beforeMasu = (v: ConjWord) => conjugate(v, 'masu').at(-3)!;
const I_ROW = 'いきしちにひみりぎじびぴ';

export const JISHO = segment('jisho', 'じしょけい', 'ย้อนหารูปพจนานุกรม', [
  lesson('c-jisho-masu', 'たべる', 'ます → คำเดิม', [
    rule(
      'jisho-masu-1',
      'のみます → のむ',
      'เสียงหน้า ます เป็น i: ส่วนใหญ่เป็นกลุ่ม 1',
      ['ตัด ます แล้วเปลี่ยนเสียง i เป็นเสียง u ในแถวเดียวกัน', 'のみます → のむ · かきます → かく · かいます → かう'],
      'masu',
      (v) => v.group === 1,
      ['nomu', 'kaku', 'kau', 'kaeru'],
      { ...reverse },
    ),
    rule(
      'jisho-masu-2',
      'たべます → たべる',
      'เสียงหน้า ます เป็น e: กลุ่ม 2 แน่นอน',
      ['ตัด ます แล้วเติม る', 'たべます → たべる · あけます → あける · ねます → ねる'],
      'masu',
      (v) => g2(v) && !I_ROW.includes(beforeMasu(v)),
      ['taberu', 'akeru', 'neru'],
      { ...reverse },
    ),
    rule(
      'jisho-masu-i2',
      'みます → みる',
      'เสียงหน้า ます เป็น i แต่เป็นกลุ่ม 2 (ต้องจำ)',
      [
        'คำเหล่านี้หน้าตาเหมือนกลุ่ม 1 แต่เป็นกลุ่ม 2: ตัด ます แล้วเติม る',
        'ในคำศัพท์ N5 ของเว็บมี 8 คำ: みる · おきる · かりる · おりる · あびる · できる · いる (มี / อยู่) · きる (ใส่เสื้อ)',
      ],
      'masu',
      (v) => g2(v) && I_ROW.includes(beforeMasu(v)),
      ['miru', 'okiru', 'kariru', 'iru-exist'],
      { ...reverse },
    ),
    rule(
      'jisho-masu-3',
      'します → する · きます → くる',
      'กลุ่ม 3 มี 2 คำ',
      ['します มาจาก する (ทำ) · きます มาจาก くる (มา)', 'きます ที่แปลว่า "ใส่เสื้อ" มาจาก きる ดูจากประโยคหรือคันจิ (来ます / 着ます)'],
      'masu',
      ['suru', 'kuru'],
      ['suru', 'kuru'],
      { ...reverse },
    ),
  ]),
  lesson('c-jisho-te', 'かう', 'て · ない → คำเดิม', [
    rule(
      'jisho-te-2',
      'たべて → たべる',
      'ตัวหน้า て ไม่ใช่ っ ん い し: กลุ่ม 2',
      ['ตัด て แล้วเติม る', 'たべて → たべる · みて → みる · かりて → かりる'],
      'te',
      (v) => g2(v),
      ['taberu', 'miru', 'kariru'],
      { ...reverse, note: 'ข้อยกเว้น: いて มาจาก いる (มี / อยู่) ก็ได้ · きて มาจาก きる (ใส่เสื้อ) หรือ くる (มา)' },
    ),
    rule(
      'jisho-te-tte',
      'かって → かう',
      'って มาจาก う・つ・る',
      ['って มาจากคำที่ลงท้าย う つ หรือ る ต้องดูว่ามีคำไหนจริง', 'かって → かう · まって → まつ · のって → のる'],
      'te',
      (v) => v.group === 1 && 'うつる'.includes(v.kana.at(-1)!),
      ['kau', 'matsu', 'noru', 'kaeru'],
      { ...reverse, note: 'いって มาจาก いく (ไป) หรือ いう (พูด) ก็ได้ ดูจากประโยค' },
    ),
    rule(
      'jisho-te-nde',
      'のんで → のむ',
      'んで มาจาก む・ぶ・ぬ',
      ['んで มาจากคำที่ลงท้าย む ぶ หรือ ぬ', 'のんで → のむ · あそんで → あそぶ · しんで → しぬ'],
      'te',
      g1('むぶぬ'),
      ['nomu', 'asobu', 'shinu'],
      { ...reverse },
    ),
    rule(
      'jisho-te-ite',
      'かいて → かく',
      'いて มาจาก く · いで มาจาก ぐ · して มาจาก す',
      ['ดูตัวท้าย: いて → く · いで → ぐ · して → す', 'かいて → かく · およいで → およぐ · はなして → はなす'],
      'te',
      (v) => g1('くぐす')(v) && v.id !== 'iku',
      ['kaku', 'oyogu', 'hanasu'],
      { ...reverse, note: 'して เฉยๆ มาจาก する (ทำ)' },
    ),
    rule(
      'jisho-nai',
      'のまない → のむ',
      'ない: เสียง a → u · เสียง i หรือ e → เติม る',
      [
        'เสียงหน้า ない เป็น a = กลุ่ม 1: เปลี่ยนเป็นเสียง u (のまない → のむ · かわない → かう)',
        'เสียงหน้า ない เป็น i หรือ e = กลุ่ม 2: เติม る (みない → みる · たべない → たべる)',
      ],
      'nai',
      (v) => (v.group === 1 && v.id !== 'aru') || g2(v),
      ['nomu', 'kau', 'miru', 'taberu'],
      { ...reverse, note: 'กลุ่ม 3: しない → する · こない → くる' },
    ),
  ]),
]);
